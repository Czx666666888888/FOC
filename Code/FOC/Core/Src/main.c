void set_pwm_duty(float d_u, float d_v, float d_w)//通过以下函数设置占空比，可以同时给三个通道设置占空比，d_u,d_v,d_w的范围是0~1，分别对应UVW三相电机的三相绕组
{
  d_u = min(d_u, 0.9);//限制占空比最大值为0.9，防止过流
  d_v = min(d_v, 0.9);
  d_w = min(d_w, 0.9);
  __disable_irq();//关闭中断，防止在设置占空比的过程中被打断，导致占空比设置不一致
  //这里如果发生中断后，可能有短暂的U相更新，但另外两项没有更新，这会对电机产生不良影响
  __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, d_u * htim1.Instance->ARR);//最后一项是占空比，范围是0~1，htim1.Instance->ARR是定时器的自动重装载寄存器的值，决定了PWM的频率
  __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, d_v * htim1.Instance->ARR);
  __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_3, d_w * htim1.Instance->ARR);//最后一项就是CCR的值，决定了PWM的占空比
  __enable_irq();//开启中断
}
